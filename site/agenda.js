function renderList(items) {
  const root = document.getElementById("agenda-list");
  if (!items.length) {
    root.innerHTML = `<p class="empty">Geen actuele agenda-items binnen deze filter.</p>`;
    return;
  }

  const works = items.filter((item) => item.theme === "Werken");
  const calendarItems = items.filter((item) => item.theme !== "Werken");
  const groups = byDate(calendarItems);
  const today = todayIso();
  if (!groups[today]) groups[today] = [];
  const schedule = Object.entries(groups)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([date, dateItems]) => `
      <section class="day-block ${date === today ? "today-marker" : ""}" data-agenda-today="${date === today ? "true" : "false"}">
        <header>
          <h2>${date === today ? `Vandaag · ${formatDateTitle(date)}` : formatDateTitle(date)}</h2>
          <p>${formatDateSummary(date, dateItems.length)}</p>
        </header>
        <div class="event-list">
          ${
            dateItems.length
              ? dateItems
                  .sort((a, b) => a.timeSlot.localeCompare(b.timeSlot) || a.title.localeCompare(b.title))
                  .map(eventTemplate)
                  .join("")
              : `<p class="empty today-empty">Geen publiek agenda-item vandaag.</p>`
          }
        </div>
      </section>
    `)
    .join("");
  root.innerHTML = `${worksOverviewTemplate(works)}${schedule}`;

  root.querySelectorAll(".event-toggle").forEach((button) => {
    button.addEventListener("click", () => {
      const id = button.dataset.id;
      openId = openId === id ? "" : id;
      const nextUrl = new URL(window.location.href);
      nextUrl.pathname = "/";
      nextUrl.search = openId ? `?event=${encodeURIComponent(openId)}` : "";
      nextUrl.hash = "";
      window.history.replaceState(null, "", nextUrl);
      render();
      document.getElementById(id)?.scrollIntoView({ block: "nearest" });
    });
  });
  root.querySelectorAll(".event-calendar").forEach((button) => {
    button.addEventListener("click", () => {
      const item = renderedAgendaItems.find((candidate) => candidate.id === button.dataset.calendarId);
      if (!item) return;
      try {
        window.AgendaIcs.downloadIndividualIcs(item);
        button.textContent = "Agendabestand klaar";
      } catch (error) {
        button.textContent = "Export niet beschikbaar";
        console.error(error);
      }
    });
  });
  if (!hasScrolledToToday) {
    window.setTimeout(() => {
      const todayBlock = document.querySelector('[data-agenda-today="true"]');
      if (!todayBlock) return;
      hasScrolledToToday = true;
      todayBlock.scrollIntoView({ block: "start" });
    }, 80);
  }
}

function renderCounts(items) {
  document.getElementById("agenda-count-value").textContent = String(items.length);
  const works = items.filter((item) => item.theme === "Werken").length;
  const calls = items.filter((item) => item.theme === "Oproep/deadline").length;
  const sport = items.filter((item) => item.theme === "Sport").length;
  const activities = items.filter((item) => item.theme === "Activiteit").length;
  document.getElementById("agenda-count-detail").textContent = `${activities} activiteiten, ${sport} sport, ${calls} oproepen, ${works} werken.`;
  const { expired, review_required: reviewRequired } = agendaReconciliation.counts;
  document.getElementById("agenda-refresh-note").textContent =
    `Officiële broncontrole ${formatSimpleDate(refreshEngine.config.retrievedAt.slice(0, 10))}: ` +
    `${expired} verlopen punten en ${reviewRequired} punten met bronconflict worden niet als actueel getoond.`;
}

function render() {
  const visible = renderedAgendaItems.filter((item) => enabledThemes.has(item.theme));
  renderControls();
  renderCounts(visible);
  renderList(visible);
}

render();

