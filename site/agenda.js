const refreshEngine = window.PUBLIC_AGENDA_REFRESH_ENGINE;
if (!refreshEngine) throw new Error("Agenda refresh metadata ontbreekt.");

// Automatische bronnen (site/agenda-feed.js). Een feed-item dat een handmatig item vervangt,
// verbergt dat handmatige item; feed-items worden nooit als herhalende reeks uitgevouwen.
const CANONICAL_HOST = "mijn-publieke-agenda-voor-district.onrender.com";
const CANONICAL_URL = `https://${CANONICAL_HOST}/`;
const agendaFeed = window.PUBLIC_AGENDA_FEED || { sources: [], items: [], supersedes: [] };
const supersededHandIds = new Set(Array.isArray(agendaFeed.supersedes) ? agendaFeed.supersedes : []);
const feedAgendaItems = (Array.isArray(agendaFeed.items) ? agendaFeed.items : []).map((item) => ({ ...item, feed: true }));
const agendaSourceItems = expandAgendaItems([...agendaItems, ...feedAgendaItems]).filter(
  (item) => item.feed || !supersededHandIds.has(item.id)
);
const agendaReconciliation = refreshEngine.reconcileAgendaItems(agendaSourceItems, todayIso(), { now: agendaNow().toISOString() });
const onCanonicalHost = window.location.hostname === CANONICAL_HOST;
// Eén UiT-sleutel geldt voor één website: UiT-items verschijnen alleen op de canonieke site.
const hiddenUitItems = onCanonicalHost ? [] : agendaReconciliation.publicItems.filter(isUitItem);
const uitgaan = window.PublicAgendaUitgaan || null;
// Versheid: alleen als de laatste geslaagde verversing ouder is dan 48 uur (een achterstand),
// blijven BRONITEMS (uit de automatische feed) die alleen daardoor als "verouderde bron" vielen nog
// STALE_GRACE_DAYS zichtbaar, gemarkeerd met "Laatst bevestigd". Handmatige items hebben die
// gratie niet nodig: ze blijven zichtbaar tot en met hun laatste dag (zie agenda-refresh.js).
// Verlopen datums, bronconflicten en onbevestigde bronnen blijven altijd verborgen.
const FRESH_LIMIT_HOURS = 48;
const STALE_GRACE_DAYS = 14;
const agendaFreshness = uitgaan
  ? uitgaan.freshness(refreshEngine.config.generatedAt, agendaNow().getTime(), FRESH_LIMIT_HOURS)
  : { known: false, stale: false, ageHours: null, generatedAt: null };
const graceAgendaItems = uitgaan
  ? agendaReconciliation.auditItems
      .filter((item) => uitgaan.inStaleGrace(item, agendaNow().getTime(), STALE_GRACE_DAYS, { backlog: agendaFreshness.stale }))
      .map((item) => ({ ...item, graceStale: true }))
  : [];
const renderedAgendaItems = [...agendaReconciliation.publicItems, ...graceAgendaItems]
  .filter((item) => onCanonicalHost || !isUitItem(item))
  .map((item) => {
    const eventType = window.PublicAgendaEventTypes?.classifyEventType(item) || "other";
    return { ...item, eventType, category: uitgaan ? uitgaan.categoryOf({ ...item, eventType }) : "other" };
  });

function isUitItem(item) {
  return item.sourceId === "stad-uit";
}

function requestedEventId() {
  const url = new URL(window.location.href);
  const pathMatch = url.pathname.match(/^\/event\/([^/]+)\/?$/);
  const hashMatch = url.hash.match(/^#event=(.+)$/);
  const value = pathMatch?.[1] || url.searchParams.get("event") || hashMatch?.[1] || "";
  try {
    return decodeURIComponent(value);
  } catch {
    return "";
  }
}

const initialEventId = requestedEventId();

// Zonder gemeenschappelijke filter (agenda-view.js nog niet geladen of niet beschikbaar) geldt de
