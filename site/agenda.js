function agendaNow() {
  return typeof window.PUBLIC_AGENDA_CLOCK === "function" ? window.PUBLIC_AGENDA_CLOCK() : new Date();
}

function scopeOf(item) {
  return item.scope === "stad" ? "stad" : "district";
}

function stadPlaceOf(item) {
  if (item.inDistrict === true) return "in";
  if (item.inDistrict === false) return "out";
  return null;
}

function passesCategory(item) {
  if (window.PUBLIC_AGENDA_VIEW) return window.PUBLIC_AGENDA_VIEW.matchesAgenda(item);
  if (!uitgaan) return true;
  if (initialEventItem && item.id === initialEventItem.id) return true;
  return defaultCategories.has(item.category);
}

// Koopzondagen en weekmarkten publiceert alleen de stad; liggen ze in district Antwerpen, dan horen
// ze ook bij de districtsweergave (anders zou "koopzondag standaard aan" nooit iets tonen).
function stadServiceInDistrict(item) {
  return scopeOf(item) === "stad" && item.inDistrict === true && ["shopping", "markets"].includes(item.category);
}

function passesScope(item) {
  const scope = scopeOf(item);
  if (enabledScopes.has("district") && stadServiceInDistrict(item)) return true;
  if (!enabledScopes.has(scope)) return false;
  if (scope !== "stad") return true;
  const place = stadPlaceOf(item);
  return place ? enabledStadPlaces.has(place) : enabledStadPlaces.size > 0;
}

function esc(value) {
  return String(value ?? "").replace(/[&<>"']/g, (character) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#039;" })[character]);
}

// Alleen https-links worden een href; al de rest (javascript:, data:, http:) valt weg.
function safeHref(value) {
  const text = String(value ?? "").trim();
  if (!/^https:\/\/[^\s"'<>]+$/i.test(text)) return "";
  try {
    return new URL(text).protocol === "https:" ? text : "";
  } catch {
    return "";
  }
}

function sourceLabel(sourceId) {
  const source = refreshEngine.config.sources[sourceId];
  return source?.label || source?.publisher || "Officiële bron";
}

function formatInstant(iso) {
  const value = Date.parse(String(iso || ""));
  if (!Number.isFinite(value)) return "";
  return new Intl.DateTimeFormat("nl-BE", {
    timeZone: "Europe/Brussels",
    day: "numeric",
    month: "long",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  }).format(new Date(value));
}

// De kalenderdag in Europe/Brussels, niet die van het toestel: een handmatig item is zichtbaar
// tot en met zijn laatste dag in Brussel en verdwijnt om middernacht Brusselse tijd.
// (Binnen de functie: todayIso() wordt al aangeroepen voordat een const hier zou bestaan.)
function todayIso() {
  const brusselsDay = new Intl.DateTimeFormat("en-CA", { timeZone: "Europe/Brussels", year: "numeric", month: "2-digit", day: "2-digit" });
  const parts = Object.fromEntries(brusselsDay.formatToParts(agendaNow()).map((part) => [part.type, part.value]));
  return `${parts.year}-${parts.month}-${parts.day}`;
}

function addDaysIso(iso, days) {
  const [year, month, day] = iso.split("-").map(Number);
  const date = new Date(year, month - 1, day);
  date.setDate(date.getDate() + days);
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
}

function dateRange(startIso, endIso, limit = 120) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(String(startIso || ""))) return [];
  const stopIso = /^\d{4}-\d{2}-\d{2}$/.test(String(endIso || "")) ? endIso : startIso;
  const dates = [];
  let current = startIso;
  while (current <= stopIso && dates.length < limit) {
    dates.push(current);
    current = addDaysIso(current, 1);
  }
  return dates;
}

function formatSimpleDate(iso) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(String(iso || ""))) return "";
  const [year, month, day] = iso.split("-").map(Number);
  return new Intl.DateTimeFormat("nl-BE", { day: "numeric", month: "long", year: "numeric" }).format(
    new Date(year, month - 1, day)
  );
}

function normalizeText(value) {
  return String(value || "")
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .toLowerCase();
}

function slugText(value) {
  return normalizeText(value)
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

function stableHash(value) {
  let hash = 0;
  const text = String(value || "");
  for (let index = 0; index < text.length; index += 1) {
    hash = (hash * 31 + text.charCodeAt(index)) >>> 0;
  }
  return hash.toString(16);
}

function weekdayIndex(iso) {
  const [year, month, day] = iso.split("-").map(Number);
  return new Date(year, month - 1, day).getDay();
}

function weekdayName(iso) {
  return ["zondag", "maandag", "dinsdag", "woensdag", "donderdag", "vrijdag", "zaterdag"][weekdayIndex(iso)] || "";
}

function recurringWeekdays(item) {
  if (item.theme === "Werken") return [];
  const text = normalizeText(item.timeText);
  const hasSignal =
    /\belke\b/.test(text) ||
    /(maandagen|dinsdagen|woensdagen|donderdagen|vrijdagen|zaterdagen|zondagen)/.test(text) ||
    /dinsdag\s*,\s*woensdag\s+en\s+donderdag/.test(text);
  if (!hasSignal) return [];
  const weekdays = new Set();
  [
    ["zondag", "zondagen", 0],
    ["maandag", "maandagen", 1],
    ["dinsdag", "dinsdagen", 2],
    ["woensdag", "woensdagen", 3],
    ["donderdag", "donderdagen", 4],
    ["vrijdag", "vrijdagen", 5],
    ["zaterdag", "zaterdagen", 6],
  ].forEach(([singular, plural, index]) => {
    if (text.includes(singular) || text.includes(plural)) weekdays.add(index);
  });
  return [...weekdays].sort((a, b) => a - b);
}

function timeSlotFromText(value) {
  const match = String(value || "").match(/(\d{1,2})(?:[.:h]\s*(\d{2}))?/i);
  if (!match) return "Uur volgt";
  return `${String(Math.min(23, Number(match[1]) || 0)).padStart(2, "0")}:${String(
    Math.min(59, Number(match[2]) || 0)
  ).padStart(2, "0")}`;
}

function occurrenceTimeText(item, occurrence) {
  if (occurrence.timeText) return occurrence.timeText;
  const raw = item.timeText || "";
  const weekday = weekdayName(occurrence.date);
  if (weekday && raw) {
    const direct = raw.match(new RegExp(`${weekday}\\s+([^;]+?)(?=\\s+en\\s+\\w+dag|;|$)`, "i"));
    if (direct?.[1]) return direct[1].trim();
  }
  return raw;
}

